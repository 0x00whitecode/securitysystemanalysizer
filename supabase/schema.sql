-- Visitor Management System database schema for Supabase
-- Run this in the Supabase SQL editor.

CREATE TABLE IF NOT EXISTS public.user (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  username text NOT NULL UNIQUE,
  password text NOT NULL,
  access text NOT NULL CHECK (access IN ('Admin', 'Security', 'Staff', 'Visitor')),
  staff_no text NOT NULL,
  is_blocked boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS public.staff (
  staff_no text PRIMARY KEY,
  name text NOT NULL,
  email text NOT NULL,
  dob text NOT NULL,
  address text NOT NULL,
  degree text NOT NULL,
  pos text NOT NULL,
  phone_no text NOT NULL,
  sex text NOT NULL,
  is_available boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS public.registration (
  r_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  dated text NOT NULL,
  vtime text NOT NULL,
  purpose text NOT NULL,
  staff_no text NOT NULL REFERENCES public.staff (staff_no) ON DELETE CASCADE,
  phone text NOT NULL,
  email text NOT NULL,
  sex text NOT NULL,
  verified boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS public.security (
  security_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  r_id bigint NOT NULL REFERENCES public.registration (r_id) ON DELETE CASCADE,
  staff_no text NOT NULL,
  visitor_status text NOT NULL DEFAULT 'Pending' CHECK (visitor_status IN ('Pending', 'Approved', 'Rejected')),
  id_type text NOT NULL,
  id_number text NOT NULL,
  check_date text NOT NULL,
  check_time text NOT NULL,
  security_action text NOT NULL,
  remarks text,
  alert_status text NOT NULL DEFAULT 'Pending' CHECK (alert_status IN ('Pending', 'Sent', 'Failed', 'Delivered'))
);

CREATE TABLE IF NOT EXISTS public.alert (
  alert_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  r_id bigint NOT NULL REFERENCES public.registration (r_id) ON DELETE CASCADE,
  staff_no text NOT NULL REFERENCES public.staff (staff_no) ON DELETE CASCADE,
  alert_type text NOT NULL,
  alert_message text NOT NULL,
  alert_date text NOT NULL,
  alert_time text NOT NULL,
  delivery_status text NOT NULL DEFAULT 'Pending' CHECK (delivery_status IN ('Pending', 'Sent', 'Failed', 'Delivered')),
  response_status text NOT NULL DEFAULT 'Pending' CHECK (response_status IN ('Pending', 'Acknowledged', 'Resolved'))
);

CREATE TABLE IF NOT EXISTS public.video_capture (
  capture_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  r_id bigint NOT NULL REFERENCES public.registration (r_id) ON DELETE CASCADE,
  photo_path text NOT NULL,
  video_path text,
  captured_at text NOT NULL DEFAULT now()::text
);

